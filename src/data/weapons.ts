export const WEAPON_MAP = new Map<string, Weapon>(WEAPONS.map((w) => [w.id, w]));

export function getWeaponById(id: string): Weapon {
  return WEAPON_MAP.get(id) || WEAPONS[0];
}

export function getRandomWeapon(rarityLimit?: WeaponRarity): Weapon {
  let pool = WEAPONS;
  if (rarityLimit) {
    const rarityOrder: WeaponRarity[] = ['common', 'uncommon', 'rare', 'epic', 'legendary'];
    const maxIdx = rarityOrder.indexOf(rarityLimit);
    pool = WEAPONS.filter((w) => rarityOrder.indexOf(w.rarity) <= maxIdx);
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getWeaponsByRarity(rarity: WeaponRarity): Weapon[] {
  return WEAPONS.filter((w) => w.rarity === rarity);
}
